#!/usr/bin/env bash
set -Eeuo pipefail
TEST_DIR="$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)"
SCRIPT_DIR="$(CDPATH='' cd -- "$TEST_DIR/.." && pwd)"

if ! command -v docker >/dev/null 2>&1 || ! docker info >/dev/null 2>&1; then
  printf 'TAP version 13\n'
  printf 'ok 1 - valid PG16 restore # SKIP docker unavailable\n'
  printf 'ok 2 - invalid SQL stops with ON_ERROR_STOP # SKIP docker unavailable\n'
  printf 'ok 3 - non-empty destination is refused # SKIP docker unavailable\n'
  printf 'ok 4 - production-like destination is refused # SKIP docker unavailable\n'
  printf 'ok 5 - wrong PostgreSQL digest/version is refused # SKIP docker unavailable\n'
  printf 'ok 6 - container volume network teardown after failure # SKIP docker unavailable\n'
  printf 'ok 7 - SIGKILL after restore reconciles and next drill succeeds # SKIP docker unavailable\n'
  printf 'ok 8 - real Docker orphan inventory empty state # SKIP docker unavailable\n'
  printf 'ok 9 - real labelled volume detection and reconcile # SKIP docker unavailable\n'
  printf '1..9\n'
  exit 0
fi

cat >&2 <<'NOTICE'
Docker integration is intentionally opt-in because it pulls/starts the pinned
PostgreSQL 16 image. Run from a disposable CI runner with:
  SCRUM167_RUN_DOCKER_INTEGRATION=1 ./integration-pg16.sh
NOTICE
[ "${SCRUM167_RUN_DOCKER_INTEGRATION:-0}" = "1" ] || exit 77

# This test intentionally delegates to the same isolated helper. A full
# synthetic 79-migration fixture is generated by create-pg16-fixture.sh so no
# production/client content is ever used.
exec "$TEST_DIR/integration-pg16-runner.sh"
